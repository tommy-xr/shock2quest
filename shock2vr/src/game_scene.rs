/// One joint's state, for ragdoll diagnostics. `separation` and the impulses
/// staying non-zero at rest mean the constraint can't be satisfied.
#[derive(Debug, Serialize, Clone)]
pub struct DebugPhysicsJoint {
    pub body1_id: u32,
    pub body2_id: u32,
    /// `"impulse"` or `"multibody"` - which joint set this came from.
    pub joint_type: String,
    /// Skeleton joint id each body represents, if it's a ragdoll body.
    pub bone1: Option<u32>,
    pub bone2: Option<u32>,
    pub anchor1: [f32; 3],
    pub anchor2: [f32; 3],
    pub separation: f32,
    /// Constraint impulses this step. Rapier does not expose these for
    /// multibody links, so they read 0 there.
    pub linear_impulse: f32,
    pub angular_impulse: f32,
}

/// A malformed collider found by the physics audit: an AABB with NaN/inf
/// bounds, zero/negative extent, or extreme coordinates. Bad AABBs poison
/// physics queries (garbage raycasts; a debug-build parry3d overflow), so this
/// is surfaced for any level on demand.
#[derive(Debug, Serialize, Clone)]
pub struct DebugColliderIssue {
    pub entity_id: Option<i32>,
    pub entity_name: Option<String>,
    /// "non_finite" | "degenerate" | "extreme".
    pub kind: String,
    pub aabb_min: [f32; 3],
    pub aabb_max: [f32; 3],
    pub is_sensor: bool,
}

/// A single quest bit (objective flag): its name, a friendly 3-state `value`
/// ("unknown"/"incomplete"/"complete"), and the exact raw `bits`. `value` is a
/// projection (COMPLETE takes precedence), so a rare combined flag (e.g.
/// INCOMPLETE|COMPLETE = 3) reads as "complete" - use `bits` when the exact
/// value matters, since scripts compare quest bits by raw value.
#[derive(Debug, Serialize, Clone)]
pub struct DebugQuestBit {
    pub name: String,
    pub value: String,
    pub bits: u32,
}

