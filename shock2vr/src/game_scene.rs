/// Abstract game scene that can be rendered and updated
/// Supports missions, cutscenes, UI screens, debug scenes, etc.
pub trait GameScene {
    /// Main update that handles all scene-specific logic including:
    /// - Player movement and physics
    /// - Collision handling
    /// - Entity updates
    /// - Input processing
    /// Returns effects for the Game layer to process
    fn update(
        &mut self,
        time: &Time,
        input_context: &InputContext,
        asset_cache: &mut AssetCache,
        game_options: &GameOptions,
        command_effects: Vec<Effect>,
    ) -> Vec<Effect>;

    /// Main render pass - returns scene objects and camera position/rotation
    fn render(
        &mut self,
        asset_cache: &mut AssetCache,
        options: &GameOptions,
    ) -> (Vec<SceneObject>, Vector3<f32>, Quaternion<f32>);

    /// VR-specific per-eye rendering
    fn render_per_eye(
        &mut self,
        _asset_cache: &mut AssetCache,
        _view: Matrix4<f32>,
        _projection: Matrix4<f32>,
        _screen_size: Vector2<f32>,
        _options: &GameOptions,
    ) -> Vec<SceneObject> {
        Vec::new()
    }

    /// Finalization step after rendering
    fn finish_render(
        &mut self,
        _asset_cache: &mut AssetCache,
        _view: Matrix4<f32>,
        _projection: Matrix4<f32>,
        _screen_size: Vector2<f32>,
    ) {
    }

    /// Process effects generated by scene update
    fn handle_effects(
        &mut self,
        _effects: Vec<Effect>,
        _global_context: &GlobalContext,
        _game_options: &GameOptions,
        _asset_cache: &mut AssetCache,
        _audio_context: &mut AudioContext<EntityId, String>,
    ) -> Vec<GlobalEffect> {
        Vec::new()
    }

    /// Called once, on the outgoing scene, just before it is replaced.
    ///
    /// A scene that started audio which outlives a single frame - anything
    /// looping - must stop it here: the [`AudioContext`] belongs to `Game` and
    /// keeps a sink alive until it drains, which a looping sink never does, so
    /// dropping the scene alone would leave it playing forever. `handle_effects`
    /// is not enough, because scenes are also replaced from paths that never
    /// run it (a debug-runtime load, a level transition).
    fn on_exit(&mut self, _audio_context: &mut AudioContext<EntityId, String>) {}

    /// Whether this scene wants a 2D mouse cursor (e.g. a menu). Flat runtimes
    /// show the OS cursor and populate `InputContext::pointer` when true; by
    /// default scenes capture the mouse for look.
    fn wants_pointer(&self) -> bool {
        false
    }

    /// Whether the in-game pause menu may open over this scene.
    ///
    /// True for scenes that run a simulation the player would want frozen -
    /// missions and the `debug_*` scenes. Frontend screens (main menu, load,
    /// game over, loading, cutscenes) are already system UI with their own way
    /// out, so pausing them is meaningless and would trap the player behind two
    /// stacked menus; they keep the default.
    fn is_pausable(&self) -> bool {
        false
    }

    /// Whether the player's collider is currently crouched (the *actual*
    /// physics state - stand-up can be refused for lack of headroom). Drives
    /// the crouch-aware camera height; non-mission scenes have no player.
    fn player_is_crouched(&self) -> bool {
        false
    }

    /// Whether a VR hand is holding a climb hold (see `crate::vr_climb`).
    /// VR runtimes freeze their physical-crouch detector while it is true.
    fn player_is_gripping(&self) -> bool {
        false
    }

    /// Degrees to pull the flat FOV in by this frame (subtracted from the
    /// base FOV), eased over a personal-UI mode's entry/exit ramp - see the
    /// cyber interface's `ui::entry_ramp`. Implementations must return 0 in
    /// VR: OpenXR view FOVs are used as-is, and rendering at a different FOV
    /// than submitted causes compositor reprojection warping. Default: no
    /// pull (non-mission scenes have no such mode).
    fn fov_pull_deg(&self, _game_options: &GameOptions) -> f32 {
        0.0
    }

    /// Peak rim-vignette intensity (0..1) this scene wants blended in this
    /// frame, on top of (not merged with) `HitFeedback`'s own damage tint -
    /// see the cyber interface's `ui::entry_ramp`. The two are drawn as
    /// separate layered quads with their own colors, so a hit still reads
    /// while a personal-UI mode is open. Default: none.
    fn use_mode_vignette_intensity(&self) -> f32 {
        0.0
    }

    /// Collision-valid, supported position to serialize for the player.
    /// Mission scenes return a specific refusal reason while transient
    /// locomotion, death, or unsupported space makes a durable save unsafe.
    fn player_save_position(&self) -> Result<Vector3<f32>, PlayerSavePoseError> {
        Err(PlayerSavePoseError::NoPlayer)
    }

    /// The death camera's contribution to this frame's view, if the player is
    /// dying. Consumed by [`crate::Game::resolve_camera`], which folds it into
    /// whatever tracked head pose the runtime resolved, so flat and VR fall the
    /// same way from one implementation (see `crate::death_camera`).
    ///
    /// `None` - the default, and every frame a live player renders - leaves the
    /// runtime's camera untouched.
    fn death_camera(&self) -> Option<DeathCameraSample> {
        None
    }

    /// Get lighting information for VR enhancement
    fn get_hand_spotlights(&self, options: &GameOptions) -> Vec<SpotLight>;

    /// Access to the ECS world (required for most game systems)
    fn world(&self) -> &World;

    /// Script runtime paired with `world`, when this scene owns one. Save code
    /// uses it for opt-in private script state; menus/cutscenes return `None`.
    fn script_world(&self) -> Option<&ScriptWorld> {
        None
    }

    /// Scene identification
    fn scene_name(&self) -> &str;

    /// Quest information access (returns current quest state from world)
    fn quest_info(&self) -> QuestInfo {
        self.world()
            .borrow::<shipyard::UniqueView<QuestInfo>>()
            .map(|q| q.clone())
            .unwrap_or_else(|_| QuestInfo::new())
    }

    /// Optional ambient audio information for the scene
    fn ambient_audio_state(&self) -> Option<AmbientAudioState> {
        None
    }

    /// Queue an entity to be triggered after scripts are initialized
    /// This is used for delayed entity triggering during level transitions
    fn queue_entity_trigger(&mut self, entity_name: String) {
        // Default implementation for scenes that don't support entity triggering
        let _ = entity_name;
    }

    /// Downcast to Any for debugging purposes
    fn as_any(&self) -> Option<&dyn Any> {
        None
    }

    /// Downcast to Any (mutable) for debugging purposes
    fn as_any_mut(&mut self) -> Option<&mut dyn Any> {
        None
    }

    /// Expose this scene's debug/introspection interface, if it has one.
    ///
    /// Implemented by full missions and by the debug scenes (which forward to
    /// their inner `MissionCore`), so the debug runtime's HTTP endpoints work
    /// against `debug_*` scenes too.
    fn as_debuggable(&self) -> Option<&dyn DebuggableScene> {
        None
    }

    /// Mutable variant of [`as_debuggable`].
    fn as_debuggable_mut(&mut self) -> Option<&mut dyn DebuggableScene> {
        None
    }
}

