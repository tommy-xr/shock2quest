/// Debug scene trait for remote debugging capabilities
///
/// This trait provides debugging and inspection capabilities for game scenes,
/// allowing remote control and analysis through the debug runtime HTTP API.
///
/// It is designed to be optionally implemented by scenes that support debugging,
/// such as Mission scenes during development and testing.
pub trait DebuggableScene {
    /// List entities in the scene, sorted by distance from player
    ///
    /// Returns a list of entity summaries with basic information suitable
    /// for debug listing. The results are sorted by distance from the player
    /// position to make nearby entities easier to find.
    ///
    /// # Arguments
    /// * `limit` - Optional maximum number of entities to return
    /// * `filter` - Optional name pattern filter (supports wildcards)
    ///
    /// # Returns
    /// Vector of entity summaries sorted by distance from player
    fn list_entities(&self, limit: Option<usize>, filter: Option<&str>) -> Vec<DebugEntitySummary>;

    /// Resolve a client-facing entity id back to the live `EntityId`.
    ///
    /// The entity endpoints expose ids as `EntityId::inner() as i32`, which
    /// keeps only the low 32 bits of the index part (the low 48 bits hold
    /// `index + 1`; the top 16 hold the generation). Reconstructing via
    /// `EntityId::from_inner(id as u64)` therefore yields a generation-0
    /// handle that is stale for any recycled slot. This looks up the live
    /// entity whose truncated id matches instead.
    ///
    /// # Returns
    /// The live `EntityId`, or None if no live entity matches
    fn resolve_entity_id(&self, id: i32) -> Option<EntityId>;

    /// Get detailed information about a specific entity
    ///
    /// Returns comprehensive entity information including properties, links,
    /// inheritance chain, and other debug-relevant data.
    ///
    /// # Arguments
    /// * `id` - Entity ID to inspect
    ///
    /// # Returns
    /// Detailed entity information, or None if entity doesn't exist
    fn entity_detail(&self, id: EntityId) -> Option<DebugEntityDetail>;

    /// Animation playback state + world-space posed skeleton for an entity
    ///
    /// Returns None when the entity has no animation player (non-animated
    /// entities). See [`DebugAnimationState`].
    fn animation_state(&self, id: EntityId) -> Option<DebugAnimationState>;

    /// Perform a physics raycast for debugging
    ///
    /// Executes a raycast using the scene's physics system with full collision
    /// group support. Results include hit information and entity details.
    ///
    /// # Arguments
    /// * `start` - Ray starting position in world coordinates
    /// * `end` - Ray ending position (direction and distance calculated from start)
    /// * `mask` - Collision groups to test against
    ///
    /// # Returns
    /// Raycast hit result with entity and collision information
    fn raycast(&self, start: Point3<f32>, end: Point3<f32>, mask: RaycastMask) -> DebugRayHit;

    /// Teleport the player to a specific position
    ///
    /// Moves the player entity to the specified world coordinates. This is
    /// useful for testing different areas of the level and debugging
    /// position-dependent behavior.
    ///
    /// # Arguments
    /// * `position` - Target position in world coordinates
    ///
    /// # Returns
    /// Ok(()) on success, or error message if teleportation fails
    fn teleport_player(&mut self, position: Vector3<f32>) -> Result<(), String>;

    /// Move the player toward `target` in a single bounded, collision-validated
    /// hop.
    ///
    /// Unlike [`teleport_player`](Self::teleport_player), which warps the player
    /// unconditionally, this clamps the displacement to a maximum distance and
    /// shape-casts the player collider along the way, stopping short of any
    /// geometry it hits. Intended for automated navigation that must stay inside
    /// the level (a closed door, for instance, blocks the move).
    ///
    /// # Arguments
    /// * `target` - Desired destination in world coordinates
    ///
    /// # Returns
    /// A [`MoveResult`](crate::physics::MoveResult) describing how far the
    /// player actually moved and whether it was blocked.
    fn move_player(&mut self, target: Vector3<f32>) -> crate::physics::MoveResult;

    /// Get the current player position for distance calculations
    ///
    /// Returns the player's current world position, used for sorting
    /// entities by distance and other spatial queries.
    ///
    /// # Returns
    /// Player position in world coordinates
    fn player_position(&self) -> Vector3<f32>;

    /// List physics rigid bodies in the scene
    ///
    /// Returns a list of physics body summaries with basic information
    /// suitable for debug listing. Includes position, velocity, and
    /// associated entity information.
    ///
    /// # Arguments
    /// * `limit` - Optional maximum number of bodies to return
    ///
    /// # Returns
    /// Vector of physics body summaries
    fn list_physics_bodies(&self, limit: Option<usize>) -> Vec<DebugPhysicsBodySummary>;

    /// Get detailed information about a specific physics body
    ///
    /// Returns comprehensive physics body information including mass,
    /// inertia, damping, collision groups, and contact information.
    ///
    /// # Arguments
    /// * `body_id` - Physics body handle/ID to inspect
    ///
    /// # Returns
    /// Detailed physics body information, or None if body doesn't exist
    fn physics_body_detail(&self, body_id: u32) -> Option<DebugPhysicsBodyDetail>;

    /// Quality/settle metrics for every active ragdoll, for the verification
    /// harness (settle speeds, floor penetration, non-adjacent interpenetration,
    /// drift). Empty when the scene has no ragdolls.
    fn ragdoll_metrics(&self) -> Vec<DebugRagdollMetrics> {
        Vec::new()
    }

    /// Every impulse + multibody joint with its anchor separation (+ applied
    /// impulse for impulse joints), for ragdoll diagnostics. Empty when the
    /// scene has no joints.
    fn list_physics_joints(&self) -> Vec<DebugPhysicsJoint> {
        Vec::new()
    }

    /// Apply a world-space impulse to a dynamic physics body by `body_id`
    /// (waking it if asleep). Debug hook for poking ragdolls headlessly - e.g.
    /// verify a sleeping corpse wakes on impact. False = no such dynamic body.
    fn apply_body_impulse(&mut self, _body_id: u32, _impulse: [f32; 3]) -> bool {
        false
    }

    /// Colliders whose world AABB is malformed (NaN/inf, degenerate, or
    /// extreme). Empty means the level's collider geometry is clean. Used to
    /// diagnose physics-query misbehavior (bad raycasts, parry3d overflow).
    fn audit_colliders(&self) -> Vec<DebugColliderIssue> {
        Vec::new()
    }

    /// Snapshot of quest bits (objective flags) the game has set, for verifying
    /// mission progress. Empty when the scene has no quest state.
    fn quest_bits(&self) -> Vec<DebugQuestBit> {
        Vec::new()
    }

    /// Set a quest bit (objective flag) - for test setup / skipping ahead.
    /// `value` is "unknown", "incomplete", or "complete". Default: unsupported.
    fn set_quest_bit(&mut self, _name: &str, _value: &str) -> Result<(), String> {
        Err("scene does not support quest bits".to_string())
    }

    /// The items the player is carrying (backpack contents plus the hand-held
    /// items), for verifying pickups. Empty when the scene has no player.
    fn player_inventory(&self) -> Vec<DebugInventoryItem> {
        Vec::new()
    }

    /// The flat-mode UI state (`GET /v1/ui`): current mode ("shooter"/"use"),
    /// the open MFD panel, and the use-mode inventory strip, if any.
    /// Default: shooter, no panel, no strip (scenes without a flat metagame
    /// UI).
    fn ui_state(&self) -> DebugUiState {
        DebugUiState {
            mode: "shooter".to_string(),
            active_panel: None,
            strip: None,
            cursor: None,
            ammo_cycle: None,
        }
    }

    /// Put an existing world entity into the player's inventory (a headless
    /// "pick up" for testing). Models a pickup - the item lands in the backpack;
    /// wielding is a separate, presentation-specific concern. Default:
    /// unsupported.
    fn give_item(&mut self, _entity_id: EntityId) -> Result<(), String> {
        Err("scene does not support giving items".to_string())
    }

    /// Level-transition triggers in this scene (where each leads + its position),
    /// so a tester can follow the real triggers between levels instead of warping
    /// explicitly. Empty when the scene has none.
    fn list_transitions(&self) -> Vec<DebugTransition> {
        Vec::new()
    }

    /// Get current input context state
    ///
    /// Returns the current input state including head rotation, hand positions,
    /// and controller values. Used for debugging input issues and understanding
    /// current control state.
    ///
    /// # Returns
    /// Current input context state as a serializable structure
    fn get_input_state(&self) -> crate::input_context::InputContext;

    /// Set or modify input context values
    ///
    /// Allows remote control of input channels for testing and debugging.
    /// Can be used to simulate controller input, head rotation, and hand positions
    /// without requiring physical VR hardware.
    ///
    /// # Arguments
    /// * `channel` - Input channel to modify (e.g., "head.rotation", "left_hand.trigger_value")
    /// * `value` - New value for the channel (format depends on channel type)
    ///
    /// # Returns
    /// true if the channel was successfully modified, false if channel doesn't exist
    ///
    /// # Examples
    /// - `set_input("head.rotation", [0.0, 0.707, 0.0, 0.707])` - Set head rotation
    /// - `set_input("right_hand.trigger_value", 1.0)` - Full trigger press
    /// - `set_input("left_hand.thumbstick", [0.5, -0.8])` - Thumbstick input
    fn set_input(&mut self, channel: &str, value: serde_json::Value) -> bool;

    /// Get the current pathfinding test status
    ///
    /// Returns the state of the interactive pathfinding test system, so
    /// remote clients (e.g. the debug runtime) can verify that triggered
    /// pathfinding actions actually executed.
    fn pathfinding_test_status(&self) -> DebugPathfindingTestStatus;

    /// Inject a script message into a specific entity.
    ///
    /// Queues the message for delivery on the next scene update, letting debug
    /// clients exercise script behaviors (damage, frob, AI signals) without a
    /// physical interaction in the world. Returns `true` if the entity is alive
    /// and the message was queued.
    fn send_entity_message(&mut self, id: EntityId, message: DebugEntityMessage) -> bool;

    /// Monotonic pathfinding query counters (None when the scene has no
    /// pathfinding data). Remote clients diff snapshots across steps to
    /// measure per-frame query load and verify the frame budget.
    fn pathfinding_stats(&self) -> Option<DebugPathfindingStats> {
        None
    }

    /// The latest path each AI computed (empty when the scene has no
    /// pathfinding data or no AI has pathed yet). Lets remote clients see
    /// where every AI is trying to go and whether its route succeeded.
    fn ai_paths(&self) -> Vec<DebugAiPathEntry> {
        Vec::new()
    }
}

/// One AI's most recent path query, for debug introspection
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DebugAiPathEntry {
    /// EntityId::inner() as i32 - the same id space as the entity endpoints
    pub entity_id: i32,
    /// Where the AI was trying to go
    pub goal: [f32; 3],
    /// "Full" (route reaches the goal), "Partial" (goal unreachable; routed
    /// to the closest reachable point), or "Failed" (no route at all)
    pub outcome: String,
    /// Waypoints of the computed route (empty for Failed)
    pub waypoints: Vec<[f32; 3]>,
    /// Index of the waypoint the steering is CURRENTLY following (its live
    /// path may lag the latest computed route above)
    pub live_next_waypoint: Option<usize>,
    /// Length of the live path being followed
    pub live_path_len: Option<usize>,
    /// World position currently steered toward
    pub live_target: Option<[f32; 3]>,
    /// Seconds without progress toward the current waypoint
    pub live_stall_seconds: Option<f32>,
}

/// Snapshot of the pathfinding service's monotonic query counters.
///
/// Counts every find_path caller - including unbudgeted ones like the
/// interactive pathfinding test - so per-frame deltas can exceed the AI
/// frame budget while those are active.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DebugPathfindingStats {
    pub queries: u64,
    pub stressed_retries: u64,
    pub no_route: u64,
}

/// A script message a debug client can inject into a specific entity.
///
/// This is intentionally a small, serde-friendly subset of the engine's full
/// `MessagePayload` enum, surfaced so remote clients (HTTP / SDK) can exercise
/// script behaviors directly without simulating a world interaction. Extend it
/// as new debug scenarios need more message kinds.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum DebugEntityMessage {
    /// Deal `amount` damage (drives `InternalSimpleHealth` / AI health).
    /// `direction` (world-space, need not be normalized) and `point` optionally
    /// describe the blow so a death ragdoll reacts to it - same data a real
    /// projectile hit carries. Omitted = directionless damage.
    Damage {
        amount: f32,
        #[serde(default)]
        direction: Option<[f32; 3]>,
        #[serde(default)]
        point: Option<[f32; 3]>,
    },
    /// Frob (use) the entity.
    Frob,
    /// Send a named AI signal.
    Signal { name: String },
    /// Force an AI's alertness level (clamped by its alert cap).
    SetAlertness {
        level: dark::properties::AIAlertLevel,
    },
    /// Switch-link activate (what a tripwire/button sends to its targets).
    TurnOn,
    /// Switch-link deactivate.
    TurnOff,
}

/// Status of the interactive pathfinding test system
#[derive(Debug, Clone)]
pub struct DebugPathfindingTestStatus {
    /// Current state: "WaitingForStart", "WaitingForGoal", or "ShowingPath"
    pub state: String,
    /// Number of waypoints in the computed test path (0 if no path computed)
    pub test_path_waypoints: usize,
}
