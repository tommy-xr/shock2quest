/// Raycast mask for collision group filtering
#[derive(Debug, Clone)]
pub struct RaycastMask {
    pub groups: Vec<String>,
}

impl RaycastMask {
    pub fn new(groups: Vec<String>) -> Self {
        Self { groups }
    }

    pub fn all() -> Self {
        Self {
            groups: vec![
                "world".to_string(),
                "entity".to_string(),
                "selectable".to_string(),
                "player".to_string(),
                "ui".to_string(),
                "hitbox".to_string(),
                "raycast".to_string(),
            ],
        }
    }
}

